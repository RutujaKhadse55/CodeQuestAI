from typing import Any, Protocol

from .models import (Diagnosis, Divergence, GuardResult, LCProblem,
                     NeutralMessage, ReferenceBundle, TestResult)

# Placeholder types; owners refine additively after the T+0:45 freeze.
FuzzResult = GuardContext = TTSResult = SttResult = Any


class Engine(Protocol):  # Backend
    def sandbox_run(self, code: str, signature: str, tests: list[dict], timeout_s: float = 2.0) -> list[TestResult]: ...
    def fuzz(self, learner_code: str, bundle: ReferenceBundle, seed: int, n: int = 200) -> FuzzResult: ...
    def trace(self, reference_code: str, learner_code: str, args: Any) -> Divergence | None: ...


class HintState(Protocol):  # Backend
    def allowed_level(self, user_id: str, problem_key: str) -> int: ...
    def record_hint(self, user_id: str, problem_key: str, level: int) -> None: ...


class Mastery(Protocol):  # Backend
    def release_pending(self, user_id: str, attempt_id: int) -> None: ...


class ReferenceBuilder(Protocol):  # AI
    def build(self, problem: LCProblem) -> ReferenceBundle: ...


class Diagnoser(Protocol):  # AI
    def diagnose(self, fuzz_vector: str, problem_slug: str, divergence: Divergence | None) -> Diagnosis: ...


class Explainer(Protocol):  # AI
    def render(self, msg: NeutralMessage, lang: str, profile: dict | None) -> str: ...


class Guard(Protocol):  # AI
    def check(self, text: str, ctx: GuardContext) -> GuardResult: ...


class Translator(Protocol):  # AI
    def translate(self, text: str, lang: str) -> str: ...


class LearnerModel(Protocol):  # AI
    def summary(self, user_id: str) -> dict: ...
    def style(self, user_id: str) -> dict: ...


class RubricScorer(Protocol):  # AI
    def score(self, transcript: str, rubric: dict, lang: str) -> tuple[float, str]: ...


class Memory(Protocol):  # Agents
    def remember(self, user_id: str, d: Diagnosis, problem_title: str) -> str: ...
    def recall(self, user_id: str, d: Diagnosis, k: int = 3) -> list[dict]: ...
    def delete_user(self, user_id: str) -> None: ...


class VoiceService(Protocol):  # Agents
    def tts(self, text: str, lang: str) -> TTSResult: ...
    def stt(self, audio: bytes, lang: str | None) -> SttResult: ...
